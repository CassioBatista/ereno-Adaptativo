"""One per-type recall table for paper 2, section 5.1: only the types with at least 100 test
rows on which two of the distributed detectors (IID, attack-based OR, attack-based k=2) differ
by at least 20 points. Step 1, seed 42. Out: ~/ereno-Adaptativo/docs/paper_v2_5_1_pertype.tex"""
import json, os
R = os.path.expanduser("~/ereno-Adaptativo/results")
OUT = os.path.expanduser("~/ereno-Adaptativo/docs/paper_v2_5_1_pertype.tex")
DET = ["IID OR", "attack-based OR", "attack-based k=2", "Centralized"]
DOMS = [("ereno", "ERENO"), ("cicids", "CICIDS2017"), ("morris4", "Morris-4"), ("ciciot", "CICIoT2023")]
MIN_N, MIN_GAP = 100, 20.0

body, report = [], []
for key, name in DOMS:
    res = json.load(open(os.path.join(R, f"ev1_step1_{key}_s42.json")))["results"]
    sel, small = [], 0
    for t in sorted(res["IID OR"]["per_type"], key=str.lower):
        n = res["IID OR"]["per_type"][t]["n"]
        rec = [100 * res[d]["per_type"][t]["recall"] for d in DET]
        if n < MIN_N:
            small += 1
            continue
        gap = max(rec[:3]) - min(rec[:3])
        if gap >= MIN_GAP:
            sel.append((t, n, rec))
    report.append(f"{name}: {len(sel)} types selected, {small} with < {MIN_N} test rows")
    if not sel:
        continue
    if body:
        body.append(r"\midrule")
    for i, (t, n, rec) in enumerate(sel):
        label = t.replace("_Attempted", " attempted").replace("_", " ")
        dom = rf"\multirow{{{len(sel)}}}{{*}}{{{name}}}" if i == 0 else ""
        body.append(f"{dom} & {label} & {n:,} & " + " & ".join(f"{v:.1f}" for v in rec) + r" \\")

out = [r"% Per-type recall, step 1 (seed 42), selected types. Generated by",
       r"% scripts/ev1_checks/pertype_table_one.py from results/ev1_step1_<domain>_s42.json.",
       r"% " + "; ".join(report),
       r"\begin{table}[htbp]", r"\centering",
       r"\caption{Recall per attack type (\%; test split, seed 42) of the types with at least "
       r"100 test rows on which IID, attack-based and attack-based $k{=}2$ differ by at least "
       r"20 points. No type of ERENO or Morris-4 meets this condition. The types with fewer "
       r"than 100 test rows (10 in CICIDS2017, 7 in CICIoT2023) are not shown; in CICIoT2023 "
       r"they follow the same pattern (IID 2.2 to 12.5\,\%, attack-based 97.4 to 100\,\%).}",
       r"\label{tab:pertype}", r"\small", r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
       r"Domain & Type & Test rows & IID & Attack-based & Attack-based, $k{=}2$ & Centralized \\",
       r"\midrule"] + body + [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
open(OUT, "w").write("\n".join(out))
print("\n".join(out))
